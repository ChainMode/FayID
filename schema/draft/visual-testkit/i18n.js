let currentLanguage = fallbackLanguage;

export function initI18n() {
  currentLanguage = resolveLanguage();
  applyLanguageSideEffects();
  return currentLanguage;
}

export function setLanguage(code) {
  currentLanguage = isSupported(code) ? code : fallbackLanguage;
  localStorage.setItem(storageKey, currentLanguage);
  applyLanguageSideEffects();
  return currentLanguage;
}

export function getLanguage() {
  return currentLanguage;
}

export function t(key, values = {}) {
  const table = messages[currentLanguage] || messages[fallbackLanguage];
  const text = table[key] ?? messages[fallbackLanguage][key] ?? key;
  return text.replace(/\{([a-zA-Z0-9_]+)\}/gu, (_, name) => String(values[name] ?? ""));
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  root.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":").map((value) => value.trim());
      if (attribute && key) element.setAttribute(attribute, t(key));
    });
  });

  document.title = t("app.title");
}

function resolveLanguage() {
  const urlLanguage = new URLSearchParams(window.location.search).get("lang");
  const savedLanguage = localStorage.getItem(storageKey);
  const browserLanguage = navigator.languages?.find((code) => isSupported(code) || isSupported(baseTag(code)));
  return normalizeLanguage(urlLanguage) || normalizeLanguage(savedLanguage) || normalizeLanguage(browserLanguage) || fallbackLanguage;
}

function normalizeLanguage(code) {
  if (!code) return "";
  if (isSupported(code)) return code;
  const base = baseTag(code);
  return isSupported(base) ? base : "";
}

function baseTag(code) {
  return code.split("-")[0];
}

function isSupported(code) {
  return languages.some((language) => language.code === code);
}

function applyLanguageSideEffects() {
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = "ltr";
}
